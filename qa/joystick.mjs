import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import fs from 'node:fs/promises';
import path from 'node:path';

const out=path.dirname(new URL(import.meta.url).pathname);
const base=process.argv[2]||'http://127.0.0.1:4173';
const browser=await chromium.launch({headless:true,...(process.env.CHROME_PATH?{executablePath:process.env.CHROME_PATH}:{})});
const report={cases:[],errors:[]};

for(const config of [{name:'portrait',width:390,height:844},{name:'landscape',width:844,height:390}]){
  const context=await browser.newContext({viewport:{width:config.width,height:config.height},isMobile:true,hasTouch:true,deviceScaleFactor:1});
  const page=await context.newPage(),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('console',m=>{if(m.type()==='error')errors.push(m.text())});
  await page.goto(base,{waitUntil:'networkidle'});
  await page.locator('#startButton').click();await page.locator('#briefingButton').click();
  const snap=()=>page.evaluate(()=>window.__afterlightDebug.snapshot());
  const joystick=page.locator('#flightJoystick'),fire=page.locator('[data-control="fire"]'),shield=page.locator('[data-control="shield"]');
  const box=await joystick.boundingBox(),fireBox=await fire.boundingBox(),shieldBox=await shield.boundingBox();
  assert.ok(box&&fireBox&&shieldBox,`${config.name} joystick, Fire, and Shield visible`);
  const center={x:box.x+box.width/2,y:box.y+box.height/2,id:1};
  const firePoint={x:fireBox.x+fireBox.width/2,y:fireBox.y+fireBox.height/2,id:2};
  const shieldPoint={x:shieldBox.x+shieldBox.width/2,y:shieldBox.y+shieldBox.height/2,id:3};
  const point=(dx,dy)=>({x:center.x+dx*box.width,y:center.y+dy*box.height,id:1});
  const session=await context.newCDPSession(page);
  const send=(type,points)=>session.send('Input.dispatchTouchEvent',{type,touchPoints:points});
  await page.evaluate(()=>{window.__engineAmounts=[];const prior=window.AfterlightAudio.engine;window.AfterlightAudio.engine=function(amount,...args){if(window.__engineAmounts.length<500)window.__engineAmounts.push(amount);return prior.call(this,amount,...args)}});
  const neutral=async(label)=>{const s=await snap();assert.equal(s.joystick?.pointerId,null,`${config.name} ${label} clears pointer`);assert.equal(s.joystick?.throttle,0,`${config.name} ${label} clears throttle`);assert.equal(s.joystick?.turn,0,`${config.name} ${label} clears turn`);const vars=await joystick.evaluate(e=>({x:e.style.getPropertyValue('--stick-x').trim(),y:e.style.getPropertyValue('--stick-y').trim()}));assert.deepEqual(vars,{x:'0px',y:'0px'},`${config.name} ${label} recenters knob`);return s;};
  await neutral('initial');
  await send('touchStart',[center]);
  await send('touchMove',[point(0,-.02)]);
  await page.waitForTimeout(100);
  const dead=await snap();
  assert.ok(dead.joystick.throttle<.05&&Math.abs(dead.joystick.turn)<.05,`${config.name} joystick deadzone`);
  const fuel0=dead.ship.fuel,angle0=dead.ship.a;
  const diagonal=point(.24,-.24);
  await send('touchMove',[diagonal]);
  await page.waitForTimeout(350);
  const active=await snap();
  assert.ok(active.joystick.throttle>.1&&Math.abs(active.joystick.turn)>.1,`${config.name} diagonal controls thrust and steer`);
  assert.ok(active.ship.fuel<fuel0&&Math.abs(active.ship.a-angle0)>.05,`${config.name} diagonal input changes actual flight`);
  const analogAudio=await page.evaluate(()=>window.__engineAmounts.filter(n=>n>.1&&n<.95));
  assert.ok(analogAudio.length>0,`${config.name} partial joystick throttle reaches engine audio API`);
  await send('touchStart',[diagonal,firePoint]);
  await page.waitForTimeout(320);
  const firing=await snap();
  assert.ok(firing.entities.bullets>0,`${config.name} second finger fires during joystick thrust`);
  await send('touchEnd',[diagonal]);
  await page.waitForTimeout(100);
  await neutral('stick-only release while Fire held');
  assert.equal(await fire.evaluate(e=>e.classList.contains('is-pressed')),true,`${config.name} Fire stays pressed when stick finger lifts`);
  await page.waitForTimeout(240);
  assert.ok((await snap()).entities.bullets>0,`${config.name} Fire continues after stick finger lifts`);
  await send('touchEnd',[]);
  await send('touchStart',[center]);await send('touchMove',[diagonal]);
  await send('touchStart',[diagonal,firePoint]);
  await send('touchEnd',[firePoint]);
  assert.equal(await fire.evaluate(e=>e.classList.contains('is-pressed')),false,`${config.name} Fire releases independently`);
  const fuelWithStick=(await snap()).ship.fuel;
  await page.waitForTimeout(220);
  const afterFireRelease=await snap();
  assert.ok(afterFireRelease.joystick.throttle>.1&&afterFireRelease.ship.fuel<fuelWithStick,`${config.name} stick keeps thrusting after Fire finger lifts`);
  await page.evaluate(()=>window.__afterlightDebug.setShip(540,-1000,0,0,0));
  await send('touchStart',[diagonal,firePoint,shieldPoint]);
  await page.waitForTimeout(260);
  const allThree=await snap();
  assert.ok(allThree.joystick.throttle>.1&&allThree.entities.bullets>0&&allThree.ship.shieldActive,`${config.name} three fingers thrust, Fire, and Shield simultaneously`);
  assert.ok(allThree.ship.shieldCharge<afterFireRelease.ship.shieldCharge,`${config.name} mobile Shield drains finite charge`);
  assert.equal(await shield.getAttribute('aria-pressed'),'true',`${config.name} Shield exposes pressed state`);
  const ring=await shield.evaluate(e=>e.style.getPropertyValue('--shield-charge'));
  assert.ok(parseFloat(ring)<100&&parseFloat(ring)>0,`${config.name} Shield ring tracks remaining charge`);
  await send('touchEnd',[shieldPoint]);
  await page.waitForTimeout(65);
  const afterShieldRelease=await snap();
  assert.equal(afterShieldRelease.ship.shieldActive,false,`${config.name} Shield releases independently`);
  assert.ok(afterShieldRelease.joystick.throttle>.1,`${config.name} stick remains held after Shield release`);
  assert.equal(await fire.evaluate(e=>e.classList.contains('is-pressed')),true,`${config.name} Fire stays held after Shield release`);
  await send('touchEnd',[firePoint]);
  assert.equal(await fire.evaluate(e=>e.classList.contains('is-pressed')),false,`${config.name} Fire releases after Shield`);
  await send('touchMove',[point(1.6,-1.3)]);
  await page.waitForTimeout(100);
  const far=await snap();
  assert.ok(Math.abs(far.joystick.dx)<=1.01&&Math.abs(far.joystick.dy)<=1.01,`${config.name} outside drag clamps analog values`);
  const knob=await page.locator('.joystick-knob').boundingBox();
  assert.ok(knob&&knob.x>=-.5&&knob.y>=-.5&&knob.x+knob.width<=config.width+.5&&knob.y+knob.height<=config.height+.5,`${config.name} knob stays on screen`);
  await send('touchEnd',[]);
  const released=await neutral('release');
  const fuelRelease=released.ship.fuel;
  await page.waitForTimeout(250);
  assert.ok(Math.abs((await snap()).ship.fuel-fuelRelease)<.2,`${config.name} release stops fuel burn`);
  await page.evaluate(()=>window.__afterlightDebug.setResources({shieldCharge:4}));
  await send('touchStart',[shieldPoint]);
  await page.waitForTimeout(160);
  const depleted=await snap();
  assert.equal(depleted.ship.shieldCharge,0,`${config.name} mobile Shield fully depletes`);
  assert.equal(depleted.ship.shieldActive,false,`${config.name} depleted Shield goes inactive`);
  await page.waitForFunction(()=>document.querySelector('[data-control="shield"]')?.classList.contains('is-depleted'),null,{timeout:500});
  assert.equal(await shield.evaluate(e=>e.classList.contains('is-depleted')),true,`${config.name} depleted visual appears`);
  await send('touchEnd',[shieldPoint]);
  await page.waitForTimeout(1750);
  const charging=await snap();
  assert.ok(charging.ship.shieldCharge>0,`${config.name} Shield recharges after release delay`);
  await send('touchStart',[shieldPoint]);
  await page.waitForTimeout(65);
  assert.equal((await snap()).ship.shieldActive,true,`${config.name} charged Shield rearms on next touch`);
  await send('touchCancel',[]);
  assert.equal((await snap()).ship.shieldActive,false,`${config.name} touch cancellation releases Shield`);
  assert.equal(await shield.evaluate(e=>e.classList.contains('is-pressed')),false,`${config.name} touch cancellation clears Shield visual`);
  await page.evaluate(()=>{window.__afterlightDebug.start(1);window.__afterlightDebug.setShip(540,-1000,0,0,0)});
  await send('touchStart',[center]);await send('touchMove',[diagonal]);await page.waitForTimeout(90);
  await send('touchCancel',[]);await neutral('cancel');
  await send('touchStart',[center]);await send('touchMove',[diagonal]);await page.waitForTimeout(90);
  await page.locator('#pauseButton').click();
  assert.equal((await snap()).mode,'paused',`${config.name} pause works during hold`);
  await neutral('pause');
  await send('touchEnd',[]);
  await page.locator('#resumeButton').click();
  await send('touchStart',[center]);await send('touchMove',[diagonal]);await page.waitForTimeout(90);
  await page.evaluate(()=>window.dispatchEvent(new Event('blur')));
  await neutral('blur');
  await send('touchEnd',[]);
  await page.locator('#resumeButton').click();
  await send('touchStart',[center]);await send('touchMove',[diagonal]);await page.waitForTimeout(90);
  await page.setViewportSize({width:config.width-1,height:config.height});
  await page.waitForTimeout(150);
  await neutral('resize');
  await send('touchCancel',[]);
  await page.locator('#pauseButton').click();await page.locator('#retryButton').click();
  assert.equal((await snap()).mode,'playing',`${config.name} retry enters play`);
  await neutral('retry');
  assert.deepEqual(errors,[],`${config.name} browser errors`);
  report.cases.push({config,dead:{throttle:dead.joystick.throttle,turn:dead.joystick.turn},active:{throttle:active.joystick.throttle,turn:active.joystick.turn,fuelUsed:fuel0-active.ship.fuel,angleChanged:active.ship.a-angle0},analogAudio:{samples:analogAudio.length,example:analogAudio[0]},firingBullets:firing.entities.bullets,threeFinger:{shieldCharge:allThree.ship.shieldCharge,ring,depleted:depleted.ship.shieldCharge,recharged:charging.ship.shieldCharge},far:{dx:far.joystick.dx,dy:far.joystick.dy},errors});
  await context.close();
}
await browser.close();
await fs.writeFile(path.join(out,'joystick-report.json'),JSON.stringify(report,null,2));
console.log(JSON.stringify({pass:true,...report},null,2));
