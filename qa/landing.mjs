import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import fs from 'node:fs/promises';
import path from 'node:path';

const root=path.dirname(new URL(import.meta.url).pathname);
const base=process.argv[2]||'http://127.0.0.1:4173';
const browser=await chromium.launch({headless:true,...(process.env.CHROME_PATH?{executablePath:process.env.CHROME_PATH}:{})});
const page=await browser.newPage({viewport:{width:1440,height:900}}),errors=[];
page.on('pageerror',e=>errors.push(e.message));
await page.goto(base,{waitUntil:'networkidle'});
await page.locator('#startButton').click();await page.locator('#briefingButton').click();
const snap=()=>page.evaluate(()=>window.__afterlightDebug.snapshot());
const initial=await snap(), pad=initial.pads[0], ground=await page.evaluate(x=>window.__afterlightDebug.ground(x),pad.x);
const position=(vx,vy,a,offset=38)=>page.evaluate(({x,y,vx,vy,a})=>window.__afterlightDebug.setShip(x,y,vx,vy,a),{x:pad.x,y:ground-offset,vx,vy,a});
const resources=(fuel,hull=100)=>page.evaluate(({fuel,hull})=>window.__afterlightDebug.setResources({fuel,hull,shieldCharge:100}),{fuel,hull});
await resources(30);await page.keyboard.down('Shift');
await position(0,180,0);await page.waitForTimeout(240);
const hard=await snap();
assert.ok(hard.ship.hull<90,`hard occupied-pad impact damages through launch invulnerability and shield: ${hard.ship.hull}`);
assert.equal(hard.ship.cargo,0,'hard impact does not collect crew');
assert.equal(hard.pads[0].occupied,true,'hard impact leaves crew on pad');
assert.ok(hard.ship.fuel<40,'hard impact does not refill fuel');
assert.ok(hard.ship.landingImpactUntil>hard.time-.5,'hard impact creates finite damage cooldown');
await page.keyboard.up('Shift');
await page.evaluate(()=>window.__afterlightDebug.start(1));
await resources(30);await position(0,5,.75,13);await page.waitForTimeout(120);
const crooked=await snap();
assert.ok(crooked.ship.hull<92,`crooked occupied-pad contact damages hull: ${crooked.ship.hull}`);
assert.equal(crooked.ship.cargo,0,'crooked landing does not rescue');
assert.equal(crooked.pads[0].occupied,true,'crooked landing leaves crew waiting');
assert.ok(crooked.ship.fuel<40,'crooked landing does not refuel');
await page.evaluate(()=>window.__afterlightDebug.start(1));
await resources(30);
await position(0,5,0,13);
await page.waitForFunction(()=>window.__afterlightDebug.snapshot().ship.cargo===1,null,{timeout:4000});
const gentle=await snap();
assert.equal(gentle.ship.cargo,1,'later gentle upright landing rescues same crew');
assert.equal(gentle.pads[0].occupied,false,'gentle landing clears occupied pad');
assert.ok(gentle.ship.fuel>=75,'gentle landing refuels');
assert.equal(gentle.ship.hull,100,'gentle landing does not damage hull');
await page.evaluate(()=>window.__afterlightDebug.start(1));
const body=(await snap()).spaceBodies[0];
await page.evaluate(b=>window.__afterlightDebug.setShip(b.x+b.radius+29,b.y+30,-110,0,.75),body);
await page.waitForTimeout(350);
const planetoid=await snap();
assert.ok(planetoid.ship.hull<85,`tilted side approach damages against solid planetoid during launch invulnerability: ${planetoid.ship.hull}`);
assert.ok(planetoid.ship.invuln>0,'planetoid damage applies before combat invulnerability expires');
assert.equal(planetoid.salvageCount,0,'tilted planetoid impact does not award station salvage');
assert.equal(planetoid.spaceBodies[0].docks,0,'tilted planetoid impact does not silently dock');
assert.ok(planetoid.ship.landingImpactUntil>planetoid.time-.5,'planetoid impact uses landing damage cooldown');
assert.deepEqual(errors,[],'no browser exceptions');
const report={initial:{invuln:initial.ship.invuln,pad},hard:{hull:hard.ship.hull,cargo:hard.ship.cargo,fuel:hard.ship.fuel,shieldActive:hard.ship.shieldActive,invuln:hard.ship.invuln},crooked:{hull:crooked.ship.hull,cargo:crooked.ship.cargo,fuel:crooked.ship.fuel},gentle:{hull:gentle.ship.hull,cargo:gentle.ship.cargo,fuel:gentle.ship.fuel},planetoid:{hull:planetoid.ship.hull,invuln:planetoid.ship.invuln,docks:planetoid.spaceBodies[0].docks,salvage:planetoid.salvageCount},errors};
await fs.writeFile(path.join(root,'landing-report.json'),JSON.stringify(report,null,2));
console.log(JSON.stringify({pass:true,...report},null,2));
await browser.close();
