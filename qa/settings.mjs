import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import fs from 'node:fs/promises';
import path from 'node:path';

const out=path.dirname(new URL(import.meta.url).pathname);
const base=process.argv[2]||'http://127.0.0.1:4173';
const defaults={gravity:1,thrust:1,fuel:1,density:1,controls:'joystick'};
const browser=await chromium.launch({headless:true,...(process.env.CHROME_PATH?{executablePath:process.env.CHROME_PATH}:{})});
const errors=[],report={pass:false,form:{},physics:{},density:{},mobile:{},errors};
const snap=page=>page.evaluate(()=>window.__afterlightDebug.snapshot());
const addErrors=page=>{page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error')errors.push(m.text())})};
const setForm=(page,patch)=>page.evaluate(patch=>{for(const [key,value] of Object.entries(patch)){const el=document.getElementById(`setting${key[0].toUpperCase()}${key.slice(1)}`);el.value=String(value);el.dispatchEvent(new Event('input',{bubbles:true}));el.dispatchEvent(new Event('change',{bubbles:true}));}},patch);
const values=page=>page.evaluate(()=>Object.fromEntries(['Gravity','Thrust','Fuel','Density','Controls'].map(name=>[name[0].toLowerCase()+name.slice(1),document.getElementById(`setting${name}`).value])));
const open=async(page,id='settingsButton')=>{await page.locator(`#${id}`).click();assert.equal(await page.locator('#settingsScreen').isVisible(),true,`${id} opens settings`)};
const apply=async page=>{await page.locator('#settingsApply').click();assert.equal(await page.locator('#settingsScreen').isVisible(),false,'Apply closes settings')};

try{
  const context=await browser.newContext({viewport:{width:1440,height:900}});
  const page=await context.newPage();addErrors(page);
  await page.goto(base,{waitUntil:'networkidle'});
  assert.deepEqual((await snap(page)).settings,defaults,'new game uses default settings');
  await open(page);
  assert.deepEqual(await values(page),{gravity:'1',thrust:'1',fuel:'1',density:'1',controls:'joystick'},'default form values');
  await page.screenshot({path:path.join(out,'settings-desktop.png')});
  await setForm(page,{gravity:1.75,thrust:1.5,fuel:.5,density:2,controls:'traditional'});
  assert.equal((await page.locator('#ratioValue').innerText()).trim(),'3.00×','efficiency preview responds to sliders');
  await page.locator('#settingsCancel').click();
  assert.deepEqual((await snap(page)).settings,defaults,'Cancel discards draft values');
  await open(page);
  assert.equal((await values(page)).gravity,'1','opening again restores saved setting');
  await setForm(page,{gravity:1.75,thrust:1.5,fuel:.5,density:2,controls:'traditional'});
  await page.locator('#settingsReset').click();
  assert.deepEqual(await values(page),{gravity:'1',thrust:'1',fuel:'1',density:'1',controls:'joystick'},'Reset edits the form to defaults');
  assert.deepEqual((await snap(page)).settings,defaults,'Reset alone does not apply');
  await setForm(page,{gravity:1.75,thrust:1.5,fuel:.5,density:2,controls:'traditional'});
  await apply(page);
  const changed=(await snap(page)).settings;
  assert.deepEqual(changed,{gravity:1.75,thrust:1.5,fuel:.5,density:2,controls:'traditional'},'Apply commits all fields');
  const stored=await page.evaluate(()=>JSON.parse(localStorage.getItem('afterlight-settings-v1')));
  assert.deepEqual(stored,changed,'Apply persists versioned settings');
  await page.reload({waitUntil:'networkidle'});
  assert.deepEqual((await snap(page)).settings,changed,'reload restores stored settings');
  await open(page);
  assert.equal((await values(page)).controls,'traditional','reload restores control selector');
  await page.locator('#settingsReset').click();await apply(page);
  assert.deepEqual((await snap(page)).settings,defaults,'Reset plus Apply restores defaults');
  report.form={changed,stored,resetApplied:(await snap(page)).settings};

  await page.locator('#startButton').click();await page.locator('#briefingButton').click();
  const activeBefore=await snap(page);
  assert.equal(activeBefore.activeDensity,1,'current sortie starts with normal density');
  await open(page);
  const pausedOpen=await snap(page);
  assert.equal(pausedOpen.mode,'paused','settings opened in flight pauses gameplay');
  const frozenTime=pausedOpen.time;await page.waitForTimeout(220);
  assert.equal((await snap(page)).time,frozenTime,'simulation freezes while settings open');
  await setForm(page,{density:2});await apply(page);
  const pending=await snap(page);
  assert.equal(pending.mode,'playing','Apply returns to flight');
  assert.equal(pending.activeDensity,1,'density change waits until next sortie');
  assert.equal(pending.settings.density,2,'saved density changes immediately');
  assert.equal(pending.turrets.length,activeBefore.turrets.length,'current enemies do not respawn on Apply');
  await page.evaluate(()=>window.__afterlightDebug.start(1));
  const swarm=await snap(page);
  assert.equal(swarm.activeDensity,2,'restart activates Swarm density');
  assert.equal(swarm.turrets.length,6,'Swarm doubles first-sector sentries');
  assert.equal(swarm.flyingEnemies.length,14,'Swarm doubles first-sector surface flyers and orbital guardians');
  await open(page);await setForm(page,{density:0});await apply(page);
  assert.equal((await snap(page)).activeDensity,2,'Peaceful stays pending during active Swarm sortie');
  await page.evaluate(()=>window.__afterlightDebug.start(1));
  const peaceful=await snap(page);
  assert.equal(peaceful.activeDensity,0,'next sortie activates Peaceful density');
  assert.equal(peaceful.turrets.length,0,'Peaceful removes sentries');
  assert.equal(peaceful.flyingEnemies.length,0,'Peaceful removes flying enemies and guardians');
  await page.locator('#pauseButton').click();
  await open(page,'pauseSettingsButton');
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('#settingsScreen').isVisible(),false,'Escape closes settings without altering the game');
  assert.equal((await snap(page)).mode,'paused','settings Escape returns to prior pause menu');
  await page.locator('#resumeButton').click();
  report.density={before:{active:activeBefore.activeDensity,turrets:activeBefore.turrets.length,enemies:activeBefore.flyingEnemies.length},pending:{active:pending.activeDensity,saved:pending.settings.density},swarm:{active:swarm.activeDensity,turrets:swarm.turrets.length,enemies:swarm.flyingEnemies.length},peaceful:{active:peaceful.activeDensity,turrets:peaceful.turrets.length,enemies:peaceful.flyingEnemies.length}};
  await context.close();

  const measure=async(patch,thrust)=>{
    const c=await browser.newContext({viewport:{width:1440,height:900}});
    await c.addInitScript(config=>localStorage.setItem('afterlight-settings-v1',JSON.stringify({...config})),{...defaults,...patch});
    const p=await c.newPage();addErrors(p);await p.goto(base,{waitUntil:'networkidle'});
    await p.locator('#startButton').click();await p.locator('#briefingButton').click();
    await p.evaluate(()=>window.__afterlightDebug.setShip(540,-1000,0,0,0));
    await p.waitForTimeout(100);const before=await snap(p);
    if(thrust)await p.keyboard.down('ArrowUp');
    await p.waitForTimeout(650);
    if(thrust)await p.keyboard.up('ArrowUp');
    const after=await snap(p);await c.close();
    return {dt:after.time-before.time,dvy:after.ship.vy-before.ship.vy,fuelUsed:before.ship.fuel-after.ship.fuel};
  };
  const gravityLow=await measure({gravity:.25},false),gravityHigh=await measure({gravity:2},false);
  assert.ok(gravityHigh.dvy>gravityLow.dvy*3,`higher gravity increases fall acceleration: ${gravityLow.dvy} vs ${gravityHigh.dvy}`);
  const thrustLow=await measure({thrust:.5},true),thrustHigh=await measure({thrust:2},true);
  assert.ok(thrustHigh.dvy<thrustLow.dvy-90,`higher thrust climbs faster: ${thrustLow.dvy} vs ${thrustHigh.dvy}`);
  const fuelLow=await measure({fuel:.25},true),fuelHigh=await measure({fuel:2},true);
  assert.ok(fuelHigh.fuelUsed>fuelLow.fuelUsed*5,`higher Fuel Use burns more: ${fuelLow.fuelUsed} vs ${fuelHigh.fuelUsed}`);
  report.physics={gravityLow,gravityHigh,thrustLow,thrustHigh,fuelLow,fuelHigh};

  const noStore=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
  await noStore.addInitScript(()=>{Storage.prototype.getItem=()=>{throw Error('storage denied')};Storage.prototype.setItem=()=>{throw Error('storage denied')}});
  const n=await noStore.newPage();addErrors(n);await n.goto(base,{waitUntil:'networkidle'});
  assert.deepEqual((await snap(n)).settings,defaults,'storage denial falls back to defaults');
  await open(n);await setForm(n,{thrust:1.75});await apply(n);
  assert.equal((await snap(n)).settings.thrust,1.75,'Apply works in memory when storage throws');
  await n.locator('#startButton').click();await n.locator('#briefingButton').click();
  assert.equal((await snap(n)).mode,'playing','storage denial does not block play');
  await noStore.close();

  for(const layout of [{name:'portrait',width:390,height:844},{name:'small-portrait',width:320,height:568},{name:'short-landscape',width:568,height:280}]){
    const c=await browser.newContext({viewport:{width:layout.width,height:layout.height},isMobile:true,hasTouch:true,deviceScaleFactor:2});
    const p=await c.newPage();addErrors(p);await p.goto(base,{waitUntil:'networkidle'});
    await open(p);
    const fit=await p.evaluate(()=>{const panel=document.querySelector('.settings-panel'),body=document.querySelector('.settings-body'),r=panel.getBoundingClientRect(),b=body.getBoundingClientRect(),v=visualViewport;return{rect:{x:r.x,y:r.y,right:r.right,bottom:r.bottom},body:{x:b.x,y:b.y,right:b.right,bottom:b.bottom},scrollHeight:body.scrollHeight,clientHeight:body.clientHeight,touchAction:getComputedStyle(body).touchAction,fontSize:parseFloat(getComputedStyle(document.querySelector('#settingDensity')).fontSize),viewport:{w:v.width,h:v.height}}});
    assert.ok(fit.rect.x>=-1&&fit.rect.y>=-1&&fit.rect.right<=fit.viewport.w+1&&fit.rect.bottom<=fit.viewport.h+1,`${layout.name} settings panel fits viewport`);
    assert.ok(fit.fontSize>=16,`${layout.name} settings form avoids iOS focus zoom`);
    if(layout.name==='short-landscape'){
      assert.ok(fit.scrollHeight>fit.clientHeight+30,'short landscape panel scrolls vertically');
      const x=Math.min(layout.width-35,(fit.body.x+fit.body.right)/2),y=Math.min(layout.height-40,fit.body.y+fit.body.bottom*.65-fit.body.y*.65);
      const session=await c.newCDPSession(p);
      await session.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x,y,id:7}]});
      await session.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x,y:y-70,id:7}]});
      await session.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x,y:y-115,id:7}]});
      await session.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
      await p.waitForTimeout(150);
      assert.ok(await p.locator('.settings-body').evaluate(el=>el.scrollTop)>0,'real touch drag scrolls short settings body');
    }
    await p.screenshot({path:path.join(out,`settings-${layout.name}.png`)});
    await p.locator('#settingsCancel').click();
    await open(p);await setForm(p,{controls:'traditional'});await apply(p);
    await p.locator('#startButton').click();await p.locator('#briefingButton').click();
    const control=await p.evaluate(()=>{const names=['left','right','thrust','fire','shield'];return{stick:getComputedStyle(document.querySelector('#flightJoystick')).display,traditional:getComputedStyle(document.querySelector('.touch-traditional')).display,buttons:Object.fromEntries(names.map(name=>{const b=document.querySelector(`[data-control="${name}"]`),r=b.getBoundingClientRect();return[name,{x:r.x,y:r.y,right:r.right,bottom:r.bottom,width:r.width,height:r.height}]}))}});
    assert.equal(control.stick,'none',`${layout.name} traditional mode hides joystick`);
    assert.notEqual(control.traditional,'none',`${layout.name} traditional buttons visible`);
    for(const [name,r] of Object.entries(control.buttons))assert.ok(r.width>0&&r.height>0&&r.x>=-1&&r.y>=-1&&r.right<=layout.width+1&&r.bottom<=layout.height+1,`${layout.name} ${name} fits viewport`);
    const pt=(name,id)=>{const r=control.buttons[name];return{x:r.x+r.width/2,y:r.y+r.height/2,id}};
    const session=await c.newCDPSession(p),points=[pt('right',1),pt('thrust',2),pt('fire',3),pt('shield',4)];
    const before=await snap(p);
    await session.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:points});
    await p.waitForTimeout(390);
    const held=await snap(p);
    assert.ok(held.ship.a>before.ship.a+.05,`${layout.name} Right rotates during multi-touch`);
    assert.ok(held.ship.fuel<before.ship.fuel,`${layout.name} Thrust burns fuel during multi-touch`);
    assert.ok(held.entities.bullets>0,`${layout.name} Fire works during multi-touch`);
    assert.ok(held.ship.shieldActive,`${layout.name} Shield works during multi-touch`);
    // CDP touchEnd lists the pointer being lifted (not the remaining contacts).
    await session.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[points[0]]});
    await p.waitForFunction(()=>!document.querySelector('[data-control="right"]').classList.contains('is-pressed'),null,{timeout:500});
    await p.waitForTimeout(60);
    const releasedAngle=(await snap(p)).ship.a;
    await p.waitForTimeout(150);
    const partial=await snap(p);
    assert.ok(Math.abs(partial.ship.a-releasedAngle)<.03,`${layout.name} releasing Right alone stops turning: ${releasedAngle}→${partial.ship.a}`);
    assert.ok(partial.ship.fuel<held.ship.fuel&&partial.entities.bullets>0&&partial.ship.shieldActive,`${layout.name} Thrust, Fire, and Shield remain active after Right lifts`);
    await session.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
    await p.waitForFunction(()=>document.querySelector('[data-control="shield"]')?.getAttribute('aria-pressed')==='false',null,{timeout:500});
    assert.equal(await p.locator('[data-control="shield"]').getAttribute('aria-pressed'),'false',`${layout.name} Shield releases`);
    for(const name of ['right','thrust','fire','shield'])assert.equal(await p.locator(`[data-control="${name}"]`).evaluate(el=>el.classList.contains('is-pressed')),false,`${layout.name} ${name} visual clears after release`);
    report.mobile[layout.name]={fit,control,held:{angleDelta:held.ship.a-before.ship.a,fuelBurn:before.ship.fuel-held.ship.fuel,bullets:held.entities.bullets,shieldActive:held.ship.shieldActive},partial:{angleDelta:partial.ship.a-held.ship.a,fuelBurn:held.ship.fuel-partial.ship.fuel}};
    await c.close();
  }
  assert.deepEqual(errors,[],'no browser errors');
  report.pass=true;
  await fs.writeFile(path.join(out,'settings-report.json'),JSON.stringify(report,null,2));
  console.log(JSON.stringify(report,null,2));
}finally{await browser.close()}
